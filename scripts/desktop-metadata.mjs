#!/usr/bin/env node
// Generates the Linux desktop entry and shared-mime-info package and the
// Windows installer's file associations from config/preview-formats.json, the
// registry the macOS Info.plist also follows.
//   node scripts/desktop-metadata.mjs          rewrite packaging/linux and packaging/windows
//   node scripts/desktop-metadata.mjs --check  fail when they are stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(readFileSync(resolve(root, 'config/preview-formats.json'), 'utf8'));
const outputs = {
  desktop: resolve(root, 'packaging/linux/burette.desktop'),
  mime: resolve(root, 'packaging/linux/burette-mime.xml'),
  windows: resolve(root, 'packaging/windows/file-associations.json'),
};

// Extensions other programs own (logs, spreadsheets, archives, Rich Text, DOS
// executables, NetCDF). Burette still opens them, but claiming their globs on
// Linux, or their default handler on Windows, would change what every file
// manager does with them.
const SHARED_EXTENSIONS = new Set([
  'abi', 'arc', 'cfg', 'checkpoint', 'chk', 'com', 'config', 'crd', 'csv', 'data', 'dms',
  'dump', 'edge', 'edr', 'fasta', 'fdef', 'fdf', 'gms', 'history', 'in', 'inp', 'json',
  'key', 'log', 'magma', 'map', 'ms', 'msj', 'nc', 'ncdf', 'netcdf', 'nw', 'out', 'par',
  'parm', 'pos', 'prm', 'qcin', 'rdf', 'rst', 'rtf', 'state', 'str', 'top', 'trj', 'tsv',
  'vasp', 'xml', 'xvg',
]);
// Types every desktop already defines; Burette only offers itself for them.
const SYSTEM_TYPES = new Set(['text/csv', 'text/tab-separated-values']);
const GENERIC_TYPES = new Set([
  'application/json', 'application/octet-stream', 'application/xml', 'application/zip',
  'text/plain', 'text/xml',
]);
const PARENT_BY_CONFORMANCE = [
  ['public.json', 'application/json'],
  ['public.xml', 'application/xml'],
  ['public.archive', 'application/zip'],
  ['public.plain-text', 'text/plain'],
  ['public.text', 'text/plain'],
];

function mimeTypeFor(format) {
  const specific = (format.mimeTypes ?? []).find((type) => !GENERIC_TYPES.has(type));
  return specific ?? `application/x-burette-${format.id}`;
}

function escapeXml(value) {
  return value.replace(/&/gu, '&amp;').replace(/</gu, '&lt;').replace(/>/gu, '&gt;');
}

const ownedTypes = [];
const offeredTypes = new Set();
for (const format of registry.formats) {
  const type = mimeTypeFor(format);
  if (SYSTEM_TYPES.has(type)) {
    offeredTypes.add(type);
    continue;
  }
  const globs = format.extensions.filter((extension) => !SHARED_EXTENSIONS.has(extension));
  if (globs.length === 0) continue;
  const parent = PARENT_BY_CONFORMANCE.find(([conformance]) => format.conformsTo?.includes(conformance))?.[1];
  ownedTypes.push({ type, description: format.description, globs, parent });
  offeredTypes.add(type);
}

const mime = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/desktop-metadata.mjs from config/preview-formats.json. -->',
  '<mime-info xmlns="http://www.freedesktop.org/standards/shared-mime-info">',
  ...ownedTypes.flatMap(({ type, description, globs, parent }) => [
    `  <mime-type type="${type}">`,
    `    <comment>${escapeXml(description)}</comment>`,
    ...(parent ? [`    <sub-class-of type="${parent}"/>`] : []),
    ...globs.map((extension) => `    <glob pattern="*.${extension}"/>`),
    '  </mime-type>',
  ]),
  '</mime-info>',
  '',
].join('\n');

// Tauri fills the {{…}} fields when it bundles the deb, rpm and AppImage.
const desktop = [
  '[Desktop Entry]',
  'Type=Application',
  'Name={{name}}',
  'Comment=View molecular structures, trajectories and chemical tables',
  'Exec={{exec}} %U',
  'Icon={{icon}}',
  'StartupWMClass={{exec}}',
  'Terminal=false',
  'Categories=Science;Chemistry;Education;',
  'Keywords=molecule;protein;PDB;mmCIF;SDF;trajectory;chemistry;',
  `MimeType=${[...[...offeredTypes].sort(), 'x-scheme-handler/burette'].join(';')};`,
  '',
].join('\n');

// The NSIS installer makes Burette the default handler of every extension it
// lists, so Windows gets only the extensions Burette owns. Explorer matches the
// last suffix alone, so compound ones (mae.gz) cannot be associated, and msp is
// a Windows Installer patch. Passed to `tauri build --config`, this array
// replaces the macOS list.
const WINDOWS_SHARED_EXTENSIONS = new Set(['msp']);
const windowsAssociations = registry.formats
  .map((format) => ({
    format,
    ext: format.extensions.filter(
      (extension) =>
        !SHARED_EXTENSIONS.has(extension) &&
        !WINDOWS_SHARED_EXTENSIONS.has(extension) &&
        !extension.includes('.'),
    ),
  }))
  .filter(({ ext }) => ext.length > 0)
  .map(({ format, ext }) => ({
    ext,
    name: `Burette.${format.id}`,
    description: format.description,
    role: 'Viewer',
  }));
const windows = `${JSON.stringify({ bundle: { fileAssociations: windowsAssociations } }, null, 2)}\n`;

const generated = { desktop, mime, windows };
if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([key, path]) => {
    try {
      return readFileSync(path, 'utf8') !== generated[key];
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    console.error(`Desktop metadata is stale: ${stale.map(([, path]) => path).join(', ')}`);
    console.error('Run: node scripts/desktop-metadata.mjs');
    process.exit(1);
  }
} else {
  for (const [key, path] of Object.entries(outputs)) writeFileSync(path, generated[key]);
}
