// Extract the original Button module, not a hand-maintained approximation.
// node scripts/sync-atlas-button.mjs --atlas /path/to/InterfaceAtlas
import { readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

const index = process.argv.indexOf('--atlas');
const atlas = index < 0 ? join(homedir(), 'Documents/Projects/InterfaceAtlas') : process.argv[index + 1];
const sheet = 'app-shared-342447930c78.css';
const source = await readFile(join(atlas, 'snapshot/assets', sheet), 'utf8');
const start = source.indexOf('._Button_eg66f_2{');
const end = source.indexOf('._Tooltip_1cofb_2{', start);
if (start < 0 || end < 0) throw new Error('Expected Atlas Button module not found');
const module = source.slice(start, end);
if ([...module].reduce((n, c) => n + (c === '{' ? 1 : c === '}' ? -1 : 0), 0) !== 0) {
  throw new Error('Button extraction crosses a stylesheet boundary');
}
const digest = createHash('sha256').update(module).digest('hex');
const css = module
  .replaceAll('_Button_eg66f_2', 'atlas-button')
  .replaceAll('_ButtonInner_eg66f_2', 'atlas-button-inner')
  .replaceAll('_ButtonLoader_eg66f_2', 'atlas-button-loader')
  .replaceAll('[data-variant', '[data-atlas-variant')
  .replaceAll('[data-size', '[data-atlas-size')
  .replaceAll('}', '}\n');
const output = `/* Generated by scripts/sync-atlas-button.mjs. Do not edit.
 * Source: InterfaceAtlas snapshot/assets/${sheet}, Button module.
 * Source module SHA-256: ${digest}
 * Only class names and Burette's namespaced variant/size attributes differ.
 */\n@layer theme, base, components, utilities;\n@layer components {\n${css}}\n`;
await writeFile(new URL('../apps/desktop/src/components/ui/button.atlas.css', import.meta.url), output);
console.log(`Original Atlas Button: ${module.length} bytes, SHA-256 ${digest}`);
