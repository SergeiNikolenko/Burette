import { spawn } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildMcpMolstar } from './build-mcp-molstar.mjs';
import { packNativeWorkspace } from './pack-native-workspace.mjs';
import { workspaceLoadingStyle, workspaceLoadingMarkup } from '../plugins/burette-agent/ui/native-workspace-loading.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
// Transport belongs to this package; the application and preview runtime can
// be built directly from the current main checkout without copying its UI.
const appRootIndex = process.argv.indexOf('--app-root');
if (appRootIndex >= 0 && !process.argv[appRootIndex + 1]) throw new Error('--app-root requires a checkout path.');
const appRoot = appRootIndex < 0 ? root : resolve(process.argv[appRootIndex + 1]);
// Bootstrap-only edits (placement, host bridge) do not change packed engines.
const bootstrapOnly = process.argv.includes('--bootstrap-only');
const shellRoot = bootstrapOnly ? null : await mkdtemp(join(tmpdir(), 'burette-mcp-shell-build-'));
const outputRoot = join(root, 'plugins/burette-agent/assets/native-workspace');
try {
  let manifest;
  if (!bootstrapOnly) {
  await new Promise((resolve, reject) => {
    const child = spawn(join(appRoot, 'node_modules/.bin/vp'), ['build'], {
      cwd: join(appRoot, 'apps/desktop'), stdio: 'inherit', env: {
        ...process.env, BURETTE_AGENT_SHELL_OUT_DIR: shellRoot,
        VITE_BURETTE_AGENT_SHELL: '1', VITE_BURETTE_WEB_ASSETS_BASE: '/__burette/runtime/',
        VITE_BURETTE_BUILD_IDENTIFIER: 'native-mcp-workspace', VITE_BURETTE_DEV_INSTANCE: 'native-mcp',
      },
    });
    child.on('error', reject);
    child.on('exit', code => code === 0 ? resolve() : reject(new Error(`Native workspace build failed: ${code}`)));
  });
  // This directory is entirely generated by this build. Do not retain obsolete
  // content-addressed copies across source revisions.
  await rm(outputRoot, { recursive: true, force: true });
  manifest = await packNativeWorkspace({ shellRoot, runtimeRoot: join(appRoot, 'PreviewExtension/Web'), outputRoot, molstar: await buildMcpMolstar(appRoot) });
  }
  const bootstrap = await Bun.build({ entrypoints: [join(root, 'plugins/burette-agent/ui/native-workspace-entry.mjs')], target: 'browser', format: 'esm', minify: true, define: { 'process.env.NODE_ENV': '"production"' },
    plugins: [{ name: 'shared-application-icons', setup(build) {
      build.onLoad({ filter: /config\/icons\/apps-sdk\.json$/u }, async () => ({
        contents: await readFile(join(appRoot, 'config/icons/apps-sdk.json'), 'utf8'), loader: 'json',
      }));
    } }],
  });
  if (!bootstrap.success) throw new Error(bootstrap.logs.join('\n'));
  const script = (await bootstrap.outputs[0].text()).replace(/<\/script/giu, '<\\/script');
  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Burette</title><style>${workspaceLoadingStyle}</style></head><body><div id="status" role="status">${workspaceLoadingMarkup}</div><div id="root"></div><script type="module">${script}</script></body></html>`;
  if (Buffer.byteLength(html) > 4 * 1024 * 1024) throw new Error('Native workspace bootstrap exceeds 4 MiB.');
  await writeFile(join(root, 'plugins/burette-agent/assets/native-workspace.html'), html);
  console.log(JSON.stringify({ applicationSource: appRoot, ...(manifest ? { nativeWorkspaceAssets: Object.keys(manifest.assets).length, entry: manifest.entry } : { bootstrapOnly: true }), networkRequired: false }));
} finally { if (shellRoot) await rm(shellRoot, { recursive: true, force: true }); }
