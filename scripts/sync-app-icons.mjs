#!/usr/bin/env node
// Regenerate the React glyph data and inline preview glyphs from the reviewed
// Apps SDK UI snapshot. This does not install dependencies or build the app.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const snapshot = JSON.parse(await readFile(new URL('config/icons/apps-sdk.json', root), 'utf8'));
const license = await readFile(new URL('config/icons/LICENSE', root), 'utf8');
const banner = `/*! ${snapshot.source.package}@${snapshot.source.version}\n${license.trim()}\n*/\n// Generated by scripts/sync-app-icons.mjs. Source: config/icons/apps-sdk.json.\n`;
const reactAttributes = (attrs) => Object.fromEntries(Object.entries(attrs).map(([key, value]) => [
  key.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()), value,
]));
const exports = Object.entries(snapshot.icons).map(([name, nodes]) => {
  // Hugeicons applies caller strokeWidth after node attributes. Tailwind's
  // stroke-none utility overrides that presentation attribute while keeping
  // node values within the renderer's string-or-number attribute contract.
  const data = nodes.map(([tag, attrs], index) => [tag, {
    ...reactAttributes(attrs),
    key: `${name}-${index}`,
    ...(attrs.stroke === 'none' ? { className: 'stroke-none' } : {}),
  }]);
  return `export const ${name} = ${JSON.stringify(data)} as const;`;
});
await writeFile(new URL('apps/desktop/src/components/ui/app-icon-data.ts', root), banner + exports.join('\n') + '\n');
const componentsPath = new URL('apps/desktop/src/components/ui/app-icons.tsx', root);
const components = (await readFile(componentsPath, 'utf8')).split('// BEGIN GENERATED EXPORTS')[0];
await writeFile(componentsPath, components + '// BEGIN GENERATED EXPORTS\n' + Object.keys(snapshot.icons)
  .map((name) => `export const ${name} = /* @__PURE__ */ appIcon("${name}");`).join('\n') + '\n');

console.log(`Updated desktop glyphs from ${snapshot.source.package}@${snapshot.source.version}`);
