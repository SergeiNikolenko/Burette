#!/usr/bin/env bun
// A reviewed subset of the OpenAI Apps SDK UI icons; no UI framework dependency.
import { mkdir, writeFile } from 'node:fs/promises';
const revision = '0f00143c7a639906f1621fe58e1b6be7b5bea46d';
const names = ['ArrowUpRight', 'OpenRight', 'ExternalLink', 'FolderOpen', 'FolderPlus', 'FolderDocumentsFinder', 'Pin', 'Unpin', 'Edit', 'Copy', 'Link', 'Download', 'Trash', 'CloseBold', 'Text', 'Cube', 'Grid', 'TableFilled', 'Plus', 'ArrowRotateCw', 'Sidebar', 'Search', 'SelectText', 'ImageSquare', 'CompareArrows'];
const destination = new URL('../apps/desktop/src/assets/openai-menu-icons/', import.meta.url);
await mkdir(destination, { recursive: true });
const icons = {};
for (const name of names) {
  const response = await fetch(`https://raw.githubusercontent.com/openai/apps-sdk-ui/${revision}/src/components/Icon/svg/${name}.tsx`);
  if (!response.ok) throw new Error(`${name}: ${response.status}`);
  const source = await response.text();
  let svg = source.match(/<svg[\s\S]*?<\/svg>/)?.[0];
  if (!svg) throw new Error(`No SVG in ${name}`);
  svg = svg.replace(/\s*\{\.\.\.props\}/g, '').replace(/width="1em" height="1em"/, 'xmlns="http://www.w3.org/2000/svg" width="32" height="32"')
    .replaceAll('currentColor', '#000').replaceAll('fillRule=', 'fill-rule=').replaceAll('clipRule=', 'clip-rule=')
    .replaceAll('strokeWidth=', 'stroke-width=').replaceAll('strokeLinecap=', 'stroke-linecap=').replaceAll('strokeLinejoin=', 'stroke-linejoin=');
  if (/[{}]|<script|href=/i.test(svg)) throw new Error(`Unexpected SVG content in ${name}`);
  icons[name] = svg.trim();
}
await writeFile(new URL('icons.json', destination), JSON.stringify(icons, null, 2) + '\n');
const license = await fetch(`https://raw.githubusercontent.com/openai/apps-sdk-ui/${revision}/LICENSE`);
if (!license.ok) throw new Error('Missing upstream license');
await writeFile(new URL('LICENSE', destination), await license.text());
await writeFile(new URL('README.md', destination), `# OpenAI Apps SDK UI menu icons\n\nSource: https://github.com/openai/apps-sdk-ui/tree/${revision}/src/components/Icon/svg\n\nMIT license; see LICENSE. Generated by \`bun scripts/vendor-menu-icons.mjs\`.\nSVG paths are unchanged. Size, XML attribute names, and black template fill are normalized for browser and AppKit menu images.\n`);
console.log(`Vendored ${names.length} OpenAI Apps SDK UI icons at ${revision}`);
