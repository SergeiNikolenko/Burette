function DropdownMenuContent({
  className,
  sideOffset = 4,
  container,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content> & {
  container?: React.ComponentProps<typeof DropdownMenuPrimitive.Portal>["container"];
}) {
  // The theme tokens live on the app shell, so a menu portalled to <body> would
  // lose its surface and text colours.
  const appShellContainer = useAppShellPortalContainer();
  return (
    <DropdownMenuPrimitive.Portal container={container ?? appShellContainer}>
      <DropdownMenuPrimitive.Content
        data-slot="dropdown-menu-content"
        sideOffset={sideOffset}
        className={cn(
          "bg-popover text-popover-foreground data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=closed]:zoom-out-95 data-[state=open]:animate-in data-[state=open]:fade-in-0 data-[state=open]:zoom-in-95 z-50 max-h-(--radix-dropdown-menu-content-available-height) min-w-[8rem] origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-[20px] p-1 shadow-[0_8px_16px_-4px_rgb(0_0_0/0.12)] ring-[0.5px] ring-popover-foreground/8",
          className,
        )}
        {...props}
      />
    </DropdownMenuPrimitive.Portal>
  );
}

