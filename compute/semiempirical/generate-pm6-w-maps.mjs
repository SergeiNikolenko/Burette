#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const input = resolve(root, "compute/semiempirical/reference/w_integrals.py");
const output = resolve(root, "crates/burrete-compute-core/src/semiempirical/pm6_w_maps.generated.rs");
const source = readFileSync(input, "utf8");

function array(name) {
  const match = source.match(new RegExp(`${name} = \\[([\\s\\S]*?)\\]`));
  if (!match) throw new Error(`Missing ${name} in ${input}`);
  const values = [...match[1].matchAll(/\b\d+\b/g)].map((entry) => Number(entry[0]));
  if (values.length !== 243 || values.some((value) => value > 52)) {
    throw new Error(`${name} must contain 243 indices in 0..=52`);
  }
  const rustName = name.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase();
  return `const ${rustName}: [u8; 243] = [${values.join(", ")}];`;
}

writeFileSync(
  output,
  `// @generated by compute/semiempirical/generate-pm6-w-maps.mjs\n\n${array("IntRf1")}\n${array("IntRf2")}\n${array("IntRep")}\n`,
);
