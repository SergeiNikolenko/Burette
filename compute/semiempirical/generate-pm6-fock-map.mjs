#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const input = resolve(root, "compute/semiempirical/reference/fock_d.py");
const output = resolve(root, "crates/burrete-compute-core/src/semiempirical/pm6_fock_map.generated.rs");
const metalOutput = resolve(root, "compute/metal/pm6-one-center-fock.v1.metal");
const source = readFileSync(input, "utf8");
const section = source.match(/PM6_FLOCAL_MAP = \[([\s\S]*?)\n\]/)?.[1];
if (!section) throw new Error(`Missing PM6_FLOCAL_MAP in ${input}`);

const rows = [...section.matchAll(/\((\d+),\s*\[([^\]]*)\],\s*\[([^\]]*)\]\)/g)]
  .map((match) => ({
    output: Number(match[1]),
    w: [...match[2].matchAll(/\d+/g)].map((entry) => Number(entry[0])),
    density: [...match[3].matchAll(/\d+/g)].map((entry) => Number(entry[0])),
  }));
if (rows.length !== 45 || rows.some((row, index) => row.output !== index || row.w.length !== row.density.length)) {
  throw new Error("PM6 Fock map must contain ordered outputs 0..44 with paired indices");
}
const offsets = [0];
const w = [];
const density = [];
for (const row of rows) {
  w.push(...row.w);
  density.push(...row.density);
  offsets.push(w.length);
}
if (w.length !== 243 || Math.max(...w) !== 242 || Math.max(...density) !== 44) {
  throw new Error("PM6 Fock map must contain 243 W references and packed density indices");
}
writeFileSync(output, `// @generated by compute/semiempirical/generate-pm6-fock-map.mjs\n\nconst PM6_FOCK_OFFSETS: [u16; 46] = [${offsets.join(", ")}];\nconst PM6_FOCK_W_INDICES: [u8; 243] = [${w.join(", ")}];\nconst PM6_FOCK_DENSITY_INDICES: [u8; 243] = [${density.join(", ")}];\n`);

const packedRows = [];
const packedColumns = [];
for (let row = 0; row < 9; row += 1) {
  for (let column = 0; column <= row; column += 1) {
    packedRows.push(row);
    packedColumns.push(column);
  }
}
writeFileSync(metalOutput, `// @generated by compute/semiempirical/generate-pm6-fock-map.mjs
#include <metal_stdlib>
using namespace metal;

constant ushort PM6_FOCK_OFFSETS[46] = {${offsets.join(", ")}};
constant uchar PM6_FOCK_W_INDICES[243] = {${w.join(", ")}};
constant uchar PM6_FOCK_DENSITY_INDICES[243] = {${density.join(", ")}};
constant uchar PM6_PACKED_ROWS[45] = {${packedRows.join(", ")}};
constant uchar PM6_PACKED_COLUMNS[45] = {${packedColumns.join(", ")}};

kernel void burrete_pm6_one_center_fock_v1(
    device const float* density [[buffer(0)]],
    device const float* w_integrals [[buffer(1)]],
    constant uint& block_count [[buffer(2)]],
    device float* fock [[buffer(3)]],
    uint gid [[thread_position_in_grid]]
) {
    if (gid >= block_count * 45u) return;
    uint block = gid / 45u;
    uint output = gid - block * 45u;
    uint density_base = block * 81u;
    uint w_base = block * 243u;
    float value = 0.0f;
    for (uint term = PM6_FOCK_OFFSETS[output]; term < PM6_FOCK_OFFSETS[output + 1u]; ++term) {
        uint packed = PM6_FOCK_DENSITY_INDICES[term];
        uint row = PM6_PACKED_ROWS[packed];
        uint column = PM6_PACKED_COLUMNS[packed];
        float population = density[density_base + row * 9u + column];
        if (row != column) population *= 2.0f;
        value += w_integrals[w_base + PM6_FOCK_W_INDICES[term]] * population;
    }
    uint row = PM6_PACKED_ROWS[output];
    uint column = PM6_PACKED_COLUMNS[output];
    fock[density_base + row * 9u + column] = value;
    fock[density_base + column * 9u + row] = value;
}
`);
