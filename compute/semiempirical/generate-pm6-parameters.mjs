#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const input = resolve(root, "compute/semiempirical/reference/parameters_PM6_MOPAC.csv");
const output = resolve(root, "crates/burette-compute-core/src/semiempirical/pm6_full_parameters.generated.rs");
const valence = new Map([
  [1, 1], [3, 1], [4, 2], [5, 3], [6, 4], [7, 5], [8, 6], [9, 7],
  [11, 1], [12, 2], [13, 3], [14, 4], [15, 5], [16, 6], [17, 7],
  [19, 1], [20, 2], [21, 3], [22, 4], [23, 5], [24, 6], [25, 7],
  [26, 8], [27, 9], [28, 10], [29, 11], [30, 12], [31, 3], [32, 4],
  [33, 5], [34, 6], [35, 7], [37, 1], [38, 2], [39, 3], [40, 4],
  [41, 5], [42, 6], [43, 7], [44, 8], [45, 9], [46, 10], [47, 11],
  [48, 12], [49, 3], [50, 4], [51, 5], [52, 6], [53, 7],
]);

const lines = readFileSync(input, "utf8").trimEnd().split(/\r?\n/);
const header = lines.shift().split(",").map((value) => value.trim());
const rows = lines
  .map((line) => Object.fromEntries(line.split(",").map((value, index) => [header[index], value.trim()])))
  .filter((row) => valence.has(Number(row.N)) && Math.abs(Number(row.U_ss || 0)) > 1e-6);
// pm6_params.py intentionally corrects these three rounded CSV fields from
// the authoritative OpenMOPAC iodine row; preserve upstream lookup precedence.
const iodine = rows.find((row) => Number(row.N) === 53);
iodine.U_dd = "-28.822603";
iodine.zeta_d = "1.875175";
iodine.beta_d = "-7.676107";
const n = (row, key) => {
  const value = Number(row[key] || 0);
  return Number.isInteger(value) ? `${value}.0` : value.toString();
};
const gaussian = (row) => [1, 2, 3, 4]
  .map((index) => `[${n(row, `Gaussian${index}_K`)}, ${n(row, `Gaussian${index}_L`)}, ${n(row, `Gaussian${index}_M`)}]`)
  .join(", ");
const entries = rows.map((row) => {
  const atomicNumber = Number(row.N);
  const orbitalCount = atomicNumber === 1 ? 1 : Math.abs(Number(row.zeta_d || 0)) > 1e-9 ? 9 : 4;
  return `    Pm6FullElementParameters { atomic_number: ${atomicNumber}, symbol: "${row.sym}", orbital_count: ${orbitalCount}, valence_electrons: ${valence.get(atomicNumber)}, uss_ev: ${n(row, "U_ss")}, upp_ev: ${n(row, "U_pp")}, udd_ev: ${n(row, "U_dd")}, zeta_s_bohr_inv: ${n(row, "zeta_s")}, zeta_p_bohr_inv: ${n(row, "zeta_p")}, zeta_d_bohr_inv: ${n(row, "zeta_d")}, beta_s_ev: ${n(row, "beta_s")}, beta_p_ev: ${n(row, "beta_p")}, beta_d_ev: ${n(row, "beta_d")}, tail_s_bohr_inv: ${n(row, "s_orb_exp_tail")}, tail_p_bohr_inv: ${n(row, "p_orb_exp_tail")}, tail_d_bohr_inv: ${n(row, "d_orb_exp_tail")}, gss_ev: ${n(row, "g_ss")}, gsp_ev: ${n(row, "g_sp")}, gpp_ev: ${n(row, "g_pp")}, gp2_ev: ${n(row, "g_p2")}, hsp_ev: ${n(row, "h_sp")}, f0sd_ev: ${n(row, "F0SD")}, g2sd_ev: ${n(row, "G2SD")}, rho_core: ${n(row, "rho_core")}, alpha_angstrom_inv: ${n(row, "alpha")}, isolated_atom_energy_ev: ${n(row, "EISOL")}, gaussian: [${gaussian(row)}], effective_charge_s: ${n(row, "z_s")}, effective_charge_p: ${n(row, "z_p")}, effective_charge_d: ${n(row, "z_d")} },`;
});
const source = `// @generated by compute/semiempirical/generate-pm6-parameters.mjs\n\npub(super) const PM6_FULL: [Pm6FullElementParameters; ${entries.length}] = [\n${entries.join("\n")}\n];\n`;
writeFileSync(output, source);
