import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { readFileSync } from 'node:fs';
const window = new Window();
const { document } = window;
const decorate = new Function('document', 'window', readFileSync(new URL('../apps/desktop/src/preview-sequence/components.js', import.meta.url), 'utf8').replace('export function', 'function') + '\nreturn decorateComponents;')(document, window);
document.body.innerHTML = `<div class="msp-sequence-chain-label" title="Chain A | 2: GUANOSINE DIPHOSPHATE">Chain A | 2: GUANOSINE DIPHOSPHATE</div><div class="msp-sequence-wrapper"><span class="msp-sequence-number">201</span><span data-seqid="0">GDP</span></div><div class="msp-sequence-chain-label" title="Chain A | 5: Water">Chain A | 5: Water</div><div class="msp-sequence-wrapper"><span data-seqid="0">HOH</span><span data-seqid="1">HOH</span></div>`;
const original = [...document.querySelectorAll('[data-seqid]')];
let updates = 0;
decorate(document.body, () => updates++);
const water = document.querySelector('.buret-water-row');
const toggle = document.querySelector('.buret-water-label button');
assert.equal(water.hidden, true);
assert.equal(toggle.textContent, 'Water · 2');
toggle.click();
decorate(document.body, () => updates++);
assert.equal(water.hidden, false, 'refresh preserves expansion');
assert.equal(toggle.getAttribute('aria-expanded'), 'true');
assert.equal(updates, 1);
assert.deepEqual([...document.querySelectorAll('[data-seqid]')], original, 'native picking nodes retain identity and order');
assert.equal(document.querySelector('[aria-label="Details for GDP A:201"]').textContent, 'A:201');
assert.equal(document.querySelectorAll('.buret-component-control').length, 2, 'refresh does not duplicate controls');
console.log('Sequence components: identity, details and water disclosure passed');
