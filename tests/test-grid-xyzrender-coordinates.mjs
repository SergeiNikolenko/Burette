import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { Window } from 'happy-dom';
const require = createRequire(import.meta.url);
const initRDKit = require('../PreviewExtension/Web/rdkit/RDKit_minimal.js');
const rdkit = await initRDKit();
const source = readFileSync('PreviewExtension/Web/grid-viewer.js', 'utf8');
const fn = name => {
  const start = source.indexOf(`  function ${name}(`);
  assert.ok(start >= 0, name);
  return source.slice(start, source.indexOf('\n  }', start) + 4);
};
const state = { rdkit, xyzrenderUse3DCoords: true, cardRenderer: 'xyzrender' };
const input = new Function('state', [ 'xyzrenderFragmentText', 'xyzrenderCardInputText', 'hasMolblockInputCoordinates', 'hasMolblockInput3DCoordinates', 'xyzrenderCardInput' ].map(fn).join('\n') + '\nreturn xyzrenderCardInput;')(state);
const row = { smiles: 'CCOc1ccccc1' }, record = { inputExtension: 'smi', text: row.smiles };
assert.deepEqual(input(row, record), { text: row.smiles + '\n', extension: 'smi' });
state.xyzrenderUse3DCoords = false;
const flat = input(row, record);
assert.equal(flat.extension, 'sdf');
const mol = rdkit.get_mol(flat.text);
assert.equal(mol.get_smiles(), 'CCOc1ccccc1');
const lines = mol.get_molblock().split('\n');
assert.ok(lines.slice(4, 13).every(line => Number(line.slice(20, 30)) === 0));
mol.delete();
state.xyzrenderUse3DCoords = true;
assert.deepEqual(input({ molblock: flat.text }, { inputExtension: 'sdf' }), { text: row.smiles + '\n', extension: 'smi' }, 'flat files get 3D generation');
const spatial = flat.text.replace('2D', '3D');
assert.equal(input({ molblock: spatial }, { inputExtension: 'sdf' }).text.split('M  END')[0], spatial.split('M  END')[0], 'existing atom coordinates and bonds retained byte-for-byte');
const window = new Window();
window.document.body.innerHTML = '<span id="rdkit-use-input-coords-control"><button id="rdkit-use-input-coords"><span data-coordinate-mode></span></button></span>';
const sync = new Function('state', 'document', 'hasInputCoordinateRows', fn('syncRdkitCoordinatesControl') + '\nreturn syncRdkitCoordinatesControl;')(state, window.document, () => false);
sync();
const button = window.document.querySelector('button');
assert.equal(button.textContent, '3D');
assert.equal(button.disabled, false);
assert.equal(button.parentElement.hidden, false, 'SMILES-only xyzrender has the coordinate switch');
state.xyzrenderUse3DCoords = false; sync();
assert.equal(button.textContent, '2D');
state.cardRenderer = 'rdkit'; sync();
assert.equal(button.parentElement.hidden, true, 'RDKit keeps its existing input-coordinate rule');
window.happyDOM.abort();
console.log('Real RDKit layouts, original poses and xyzrender coordinate control passed');
