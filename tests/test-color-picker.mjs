import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Window } from 'happy-dom';
const window = new Window();
new Function('window', 'document', 'Event', readFileSync(new URL('../PreviewExtension/Web/color-picker.js', import.meta.url), 'utf8'))(window, window.document, window.Event);
const changes = [];
let commits = 0;
const panel = window.BuretteColorPicker.create(0x1277aa, value => changes.push(value), () => { commits++; });
window.document.body.append(panel);
const hex = panel.querySelector('input[type="text"]');
const hue = panel.querySelector('input[type="range"]');
const field = panel.querySelector('[role="slider"]');
assert.equal(hex.value, '#1277aa');
hex.value = '#ff0000';
hex.dispatchEvent(new window.Event('change'));
assert.deepEqual(changes, [0xff0000]);
hue.value = '120';
hue.dispatchEvent(new window.Event('input'));
assert.equal(hex.value, '#00ff00');
assert.deepEqual(changes, [0xff0000, 0x00ff00], 'dragging updates the scene immediately');
assert.equal(commits, 1);
hue.dispatchEvent(new window.Event('change'));
assert.deepEqual(changes, [0xff0000, 0x00ff00, 0x00ff00]);
assert.equal(commits, 2);
hex.value = 'invalid';
hex.dispatchEvent(new window.Event('change'));
assert.equal(hex.getAttribute('aria-invalid'), 'true');
assert.equal(changes.length, 3);
field.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true, cancelable: true }));
assert.equal(hex.value, '#00fc00');
assert.equal(changes.at(-1), 0x00fc00);
window.happyDOM.abort();
console.log('Custom colour HEX, HSV, validation and keyboard editing passed');
