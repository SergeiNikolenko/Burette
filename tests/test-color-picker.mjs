import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Window } from 'happy-dom';
const window = new Window();
new Function('window', 'document', 'Event', readFileSync(new URL('../PreviewExtension/Web/color-picker.js', import.meta.url), 'utf8'))(window, window.document, window.Event);
const changes = [];
let commits = 0;
const panel = window.BuretteColorPicker.create(0x1277aa, value => changes.push(value), () => { commits++; });
window.document.body.append(panel);
const hex = panel.querySelector('input[type="text"]');
let buttons = [...panel.querySelectorAll('button')];
assert.equal(hex.value, '#1277aa', 'custom existing colours remain exact');
assert.equal(buttons.length, 40, 'eight colour families have five vertical shades');
const blue = buttons[0];
blue.click();
assert.deepEqual(changes, [0xd1c9e3]);
assert.equal(commits, 1, 'one palette pick is one committed scene edit');
assert.equal(hex.value, '#d1c9e3');
assert.equal(blue.getAttribute('aria-pressed'), 'true');
blue.focus();
blue.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true, cancelable: true }));
assert.equal(window.document.activeElement, buttons[8], 'arrow down follows eight-column shade layout');
window.document.activeElement.click();
assert.equal(blue.getAttribute('aria-pressed'), 'false');
assert.equal(changes.at(-1), Number(buttons[8].dataset.color));
const select = panel.querySelector('select');
select.value = '3';
select.dispatchEvent(new window.Event('change'));
buttons = [...panel.querySelectorAll('button')];
assert.equal(buttons.length, 25, 'complete Mol* chain palette is available');
buttons[24].click();
assert.equal(changes.at(-1), 0xb3b3b3);
hex.value = '#1277aa';
hex.dispatchEvent(new window.Event('change'));
assert.equal(changes.at(-1), 0x1277aa);
assert.equal(buttons.some(button => button.getAttribute('aria-pressed') === 'true'), false);
const count = changes.length;
hex.value = 'invalid';
hex.dispatchEvent(new window.Event('change'));
assert.equal(hex.getAttribute('aria-invalid'), 'true');
assert.equal(changes.length, count);
let escapedWheel = false;
window.document.body.addEventListener('wheel', () => { escapedWheel = true; });
panel.dispatchEvent(new window.WheelEvent('wheel', { deltaX: 50, bubbles: true }));
assert.equal(escapedWheel, false, 'palette wheel must not rotate the molecule');
// Exercise the real menu rail, including the reduced-runtime fallback.
const viewer = readFileSync(new URL('../PreviewExtension/Web/viewer.js', import.meta.url), 'utf8');
const start = viewer.indexOf('  function sceneTreeMenuSwatches(');
const end = viewer.indexOf('\n  // A representation carries', start);
const createSwatches = new Function('window', 'document', 'SCENE_TREE_UNIFORM_COLORS', 'sceneTreeColorHex',
  `let sceneTreeColorPickerMissingReported = false; const debug = () => {}; ${viewer.slice(start, end)}; return sceneTreeMenuSwatches;`)(
  window, window.document, window.BuretteColorPicker.presets, value => '#' + value.toString(16).padStart(6, '0'));
window.BuretteColorPicker = undefined;
const menu = window.document.createElement('div');
createSwatches(menu, 'Molecule', 'color', null);
const rail = menu.querySelector('.buret-tree-swatch-rail');
Object.defineProperties(rail, { scrollWidth: { value: 240 }, clientWidth: { value: 160 } });
rail.dispatchEvent(new window.WheelEvent('wheel', { deltaX: 40, cancelable: true }));
assert.equal(rail.scrollLeft, 40, 'horizontal wheel moves the swatches');
rail.dispatchEvent(new window.WheelEvent('wheel', { deltaY: 2, deltaMode: 1, cancelable: true }));
assert.equal(rail.scrollLeft, 72, 'ordinary mouse wheel supports line units');
const pinch = new window.WheelEvent('wheel', { deltaY: 10, cancelable: true });
// happy-dom's WheelEvent does not forward modifier keys from its initializer.
Object.defineProperty(pinch, 'ctrlKey', { value: true });
rail.dispatchEvent(pinch);
assert.equal(rail.scrollLeft, 72, 'pinch gestures do not scroll colours');
window.happyDOM.abort();
console.log('Palette selection, undo commits, keyboard navigation, HEX and wheel isolation passed');
