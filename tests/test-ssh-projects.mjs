import assert from 'node:assert/strict';
const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
globalThis.window = new EventTarget();
const { saveSshProject, saveSshConnection, removeSshConnection, removeSshProject, sshList, sshPreview, sshDeleteFolder } = await import('../apps/desktop/src/lib/ssh-projects.ts');
const state = () => JSON.parse(values.get('burette.ssh-projects.v1'));
const first = { id: 'one', name: 'Proteins', host: 'research', root: '/data/proteins' };
saveSshProject(first);
saveSshProject({ ...first, id: 'two', root: '/data/ligands' });
saveSshProject({ ...first, pinned: true, section: 'Science' });
assert.deepEqual(state().projects.map(p => p.id), ['one', 'two']);
assert.equal(state().projects[0].section, 'Science');
assert.equal(state().projects[0].pinned, true);
assert.equal(state().connections.length, 1);
const color = state().connections[0].color;
assert.ok(['cyan', 'blue', 'purple'].includes(color));
saveSshConnection({ host: 'research', name: 'Lab', enabled: false });
assert.equal(state().connections[0].color, color);
await assert.rejects(sshList('research', '/data'), /disabled/);
await assert.rejects(sshPreview(first, 'protein.pdb'), /disabled/);
await assert.rejects(sshDeleteFolder(first, 'folder'), /disabled/);
removeSshProject('one');
assert.equal(state().connections.length, 1);
assert.deepEqual(state().projects.map(p => p.id), ['two']);
removeSshConnection('research');
assert.deepEqual(state(), { projects: [], connections: [] });
for (let i = 0; i < 100; i++) saveSshProject({ ...first, id: String(i) });
assert.throws(() => saveSshProject({ ...first, id: 'overflow' }), /100 SSH/);
assert.equal(state().projects.length, 100);
console.log('SSH project persistence, shared host lifecycle, disabled access and capacity passed');
